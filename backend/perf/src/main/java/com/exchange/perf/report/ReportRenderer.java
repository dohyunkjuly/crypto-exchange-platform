package com.exchange.perf.report;

import com.exchange.perf.report.Report.Measurement;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;

/**
 * The records of one or more runs, as the page a reader sees. The newest record wins when a
 * metric was measured twice on the same topology, so a re-run of one benchmark refreshes its
 * rows and leaves the rest. A metric measured on both topologies gets both columns.
 *
 * <p>Usage: {@code ReportRenderer <output.md> <results dir>...}; every {@code results.jsonl}
 * under the given directories is read.
 */
public final class ReportRenderer {

    private static final DateTimeFormatter DAY = DateTimeFormatter.ofPattern("yyyy-MM-dd").withZone(ZoneOffset.UTC);

    public static void main(String[] args) throws IOException {
        Path out = Path.of(args[0]);
        List<Measurement> all = new ArrayList<>();
        for (int i = 1; i < args.length; i++) {
            Path file = Path.of(args[i]).resolve("results.jsonl");
            for (String line : Report.lines(file)) {
                if (!line.isBlank()) all.add(Report.parse(line));
            }
        }
        if (all.isEmpty()) {
            System.err.println("no records under " + String.join(", ", List.of(args).subList(1, args.length)) + "; run the benchmarks first");
            System.exit(1);
        }
        Files.writeString(out, render(all));
        System.out.println("wrote " + out + " from " + all.size() + " records");
    }

    static String render(List<Measurement> all) {
        // section -> metric -> topology -> newest measurement
        Map<String, Map<String, Map<String, Measurement>>> table = new LinkedHashMap<>();
        for (String s : Report.sections()) table.put(s, new LinkedHashMap<>());
        all.stream().sorted((a, b) -> Long.compare(a.at(), b.at())).forEach(m ->
                table.computeIfAbsent(m.section(), k -> new LinkedHashMap<>())
                        .computeIfAbsent(m.metric(), k -> new TreeMap<>())
                        .put(m.topology(), m));
        boolean cluster = all.stream().anyMatch(m -> "cluster".equals(m.topology()));
        Measurement latest = all.stream().max((a, b) -> Long.compare(a.at(), b.at())).orElseThrow();

        StringBuilder md = new StringBuilder();
        md.append("# Performance report\n\n");
        md.append("Generated by `./gradlew perf` on ").append(DAY.format(java.time.Instant.ofEpochMilli(latest.at()))).append(". ")
          .append("Every number is one run on one machine: ").append(Machine.describe()).append(". ")
          .append("What the numbers mean, and how to run this yourself: [performance.md](performance.md).\n\n");
        if (cluster) {
            md.append("Two columns: a single broker (the laptop default) and three brokers with every topic ")
              .append("replicated and `acks=all` (the shape a deployment runs).\n\n");
        }
        for (Map.Entry<String, Map<String, Map<String, Measurement>>> section : table.entrySet()) {
            if (section.getValue().isEmpty()) continue;
            md.append("## ").append(section.getKey()).append("\n\n");
            md.append(cluster ? "| Metric | Single broker | Three brokers | Workload |\n|---|---|---|---|\n"
                              : "| Metric | Result | Workload |\n|---|---|---|\n");
            List<Map.Entry<String, Map<String, Measurement>>> rows = new ArrayList<>(section.getValue().entrySet());
            rows.sort((a, b) -> {
                int byRank = Integer.compare(Sections.rank(a.getKey()), Sections.rank(b.getKey()));
                return byRank != 0 ? byRank : Long.compare(
                        a.getValue().values().iterator().next().at(), b.getValue().values().iterator().next().at());
            });
            for (Map.Entry<String, Map<String, Measurement>> row : rows) {
                Measurement any = row.getValue().values().iterator().next();
                md.append("| ").append(row.getKey()).append(" | ").append(cell(row.getValue().get("single")));
                if (cluster) md.append(" | ").append(cell(row.getValue().get("cluster")));
                md.append(" | ").append(any.workload()).append(" |\n");
            }
            md.append('\n');
            List<String> meanings = rows.stream()
                    .map(r -> r.getValue().values().iterator().next())
                    .filter(m -> m.meaning() != null && !m.meaning().isBlank())
                    .map(m -> "- **" + m.metric() + "**: " + m.meaning())
                    .toList();
            if (!meanings.isEmpty()) md.append(String.join("\n", meanings)).append("\n\n");
        }
        return md.toString();
    }

    private static String cell(Measurement m) {
        if (m == null) return "—";
        if (Report.isLatency(m)) {
            return String.format(Locale.ROOT, "p50 **%s ms** · p95 %s · p99 %s (n=%d)",
                    Report.number(m.p50()), Report.number(m.p95()), Report.number(m.p99()), m.samples());
        }
        if (m.unit().endsWith("slower") && m.value() < 0) {
            // Faster with snapshots on is noise, not a gain: say so, and keep the measurement.
            return "**no measurable cost** (" + Report.number(m.value()) + " %, inside the run-to-run spread)";
        }
        return "**" + Report.number(m.value()) + "** " + m.unit();
    }
}
