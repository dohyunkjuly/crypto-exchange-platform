// The schema. Flyway migrations under src/main/resources/db/migration (one baseline per
// domain), dev and test data under db/seed, plus the JPA, Flyway and MySQL dependencies
// every domain module and app needs.
//
// No entities here -- those live with their domain under libs/domain. What stays
// centralized is the migration sequence, because it has to be:
// Flyway rejects duplicate version numbers across the classpath, and ordering is global
// (spot names wallet assets, so V2__wallet runs before V4__spot). One database,
// one ordered history.
//
// Java's answer to Prisma is deliberately two tools rather than one. Flyway owns the
// SCHEMA -- versioned .sql that run in order, exactly once each, recorded in
// flyway_schema_history. Nothing is generated by diffing; you write the SQL. JPA owns the
// QUERIES. `ddl-auto: validate` lets Hibernate check that entities still match, never
// change anything.

plugins {
    `java-library`
    alias(libs.plugins.spring.dependency.management)
}

dependencyManagement {
    imports {
        mavenBom("org.springframework.boot:spring-boot-dependencies:${libs.versions.springBoot.get()}")
    }
}

dependencies {
    api(project(":libs:common"))

    api(libs.spring.boot.starter.data.jpa)

    implementation(libs.flyway.core)
    runtimeOnly(libs.flyway.mysql)
    // runtimeOnly: your code never imports the driver. It only has to be on the classpath
    // at run time so the JDBC URL resolves to something.
    runtimeOnly(libs.mysql.connector)
}
